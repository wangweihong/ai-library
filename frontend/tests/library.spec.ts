test('conflict keeps draft and reload needs confirmation', async ({ page, request }) => {
  const row = await (await request.post('/api/v1/prompts', { data: { prompt: `${marker} conflict` } })).json()
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await page.getByRole('button', { name: `编辑提示词 ${row.id}`, exact: true }).click()
  await page.getByRole('textbox', { name: '提示词正文', exact: true }).fill('keep my draft')
  await request.patch(`/api/v1/prompts/${row.id}`, { data: { version: row.version, prompt: 'changed elsewhere' } })
  await page.getByRole('button', { name: /保存修改/ }).click()
  await expect(page.getByRole('alert')).toContainText('其他客户端修改')
  await expect(page.getByRole('textbox', { name: '提示词正文', exact: true })).toHaveValue('keep my draft')
  await page.getByRole('button', { name: '重新加载', exact: true }).click()
  await page.getByRole('button', { name: '放弃修改', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '提示词正文', exact: true })).toHaveValue('changed elsewhere')
})

test('save failure retains draft, keyboard save works after retry', async ({ page }) => {
  await page.getByRole('button', { name: '＋ 新建提示词', exact: true }).first().click()
  await page.getByRole('textbox', { name: '提示词正文', exact: true }).fill(`${marker} keyboard save`)
  await page.route('**/api/v1/prompts', route => route.request().method() === 'POST'
    ? route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"测试连接失败"}' }) : route.continue())
  await page.getByRole('textbox', { name: '提示词正文', exact: true }).press('Control+s')
  await expect(page.getByRole('alert')).toContainText('测试连接失败')
  await expect(page.getByRole('textbox', { name: '提示词正文', exact: true })).toHaveValue(`${marker} keyboard save`)
  await page.unroute('**/api/v1/prompts')
  await page.getByRole('textbox', { name: '提示词正文', exact: true }).press('Control+s')
  await expect(page.locator('.toast')).toContainText('已保存')
})

