test('hover does not overwrite dirty draft and discard guard works', async ({ page, request }) => {
  const first = await (await request.post('/api/v1/prompts', { data: { prompt: `${marker} first` } })).json()
  const second = await (await request.post('/api/v1/prompts', { data: { prompt: `${marker} second` } })).json()
  await page.getByRole('button', { name: '刷新', exact: true }).click()
  await page.getByRole('button', { name: `编辑提示词 ${first.id}`, exact: true }).click()
  await page.getByRole('textbox', { name: '提示词正文', exact: true }).fill('an unsaved draft')
  await page.getByRole('button', { name: `编辑提示词 ${second.id}`, exact: true }).hover()
  await expect(page.getByRole('complementary', { name: '只读快速预览' })).toContainText('second')
  await expect(page.getByRole('textbox', { name: '提示词正文', exact: true })).toHaveValue('an unsaved draft')
  await page.getByRole('button', { name: `编辑提示词 ${second.id}`, exact: true }).click()
  await expect(page.getByRole('dialog', { name: '有尚未保存的修改' })).toBeVisible()
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '提示词正文', exact: true })).toHaveValue('an unsaved draft')
  await page.getByRole('button', { name: `编辑提示词 ${second.id}`, exact: true }).click()
  await page.getByRole('button', { name: '放弃修改', exact: true }).click()
  await expect(page.getByRole('textbox', { name: '提示词正文', exact: true })).toHaveValue(`${marker} second`)
})

