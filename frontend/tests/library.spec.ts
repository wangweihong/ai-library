test('selection survives pagination and resets when filters change', async ({ page, request }) => {
  const needle = `${marker}-pages`
  for (let i = 0; i < 55; i++) await request.post('/api/v1/prompts', { data: { prompt: `${needle} ${i}` } })
  await page.getByRole('textbox', { name: '搜索正文或 ID' }).fill(needle)
  await page.getByRole('textbox', { name: '搜索正文或 ID' }).press('Enter')
  await expect(page.locator('.prompt-card')).toHaveCount(50)
  await page.getByRole('checkbox', { name: '当前页', exact: true }).check()
  await expect(page.locator('.selection-toolbar')).toContainText('已选 50 条')
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.locator('.prompt-card')).toHaveCount(5)
  await page.locator('.card-check input').first().check()
  await expect(page.locator('.selection-toolbar')).toContainText('已选 51 条')
  await page.getByRole('button', { name: '追加标签', exact: true }).click()
  await page.getByRole('textbox', { name: '批量操作标签' }).fill('cross-page')
  await page.getByRole('button', { name: '预览影响范围', exact: true }).click()
  await expect(page.locator('.batch-confirm strong')).toHaveText('51')
  await page.getByRole('button', { name: '确认应用', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '选择全部筛选结果', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索正文或 ID' }).fill(`${marker}-no-match`)
  await page.getByRole('textbox', { name: '搜索正文或 ID' }).press('Enter')
  await expect(page.locator('.batch-toolbar')).toHaveCount(0)
})
